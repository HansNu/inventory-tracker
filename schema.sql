-- inventory-tracker — database schema
--
-- Creates the four tables the API expects, so the project runs against a local
-- Postgres with no Supabase account. Applied automatically by docker-compose on
-- first start; see README.
--
-- Nullability here follows the Go models rather than guesswork: a pointer field
-- (*string) is a nullable column, a value field is NOT NULL. That keeps the
-- database and the structs telling the same story.

-- ─────────────────────────────────────────────────────────────────────────────
-- category_group — the top of the hierarchy. group_name is UNIQUE because two
-- other tables reference it by name rather than by id.
-- ─────────────────────────────────────────────────────────────────────────────
CREATE TABLE category_group (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_name varchar     NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    update_at  timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT category_group_group_name_key UNIQUE (group_name)
);

-- ─────────────────────────────────────────────────────────────────────────────
-- users
--
-- category_group doubles as the role: middleware.RoleMiddleware("IT") gates the
-- admin routes on this value, which is why it is a foreign key and not free text.
--
-- NOTE: the UNIQUE constraint on username does not exist in the Supabase
-- database. It is added here deliberately — see README. Without it, the
-- ExistsByUsername check in authService is the only thing preventing duplicate
-- accounts, and two simultaneous registrations can both pass that check before
-- either one inserts.
-- ─────────────────────────────────────────────────────────────────────────────
CREATE TABLE users (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           varchar     NOT NULL,
    category_group varchar     NOT NULL,
    username       varchar     NOT NULL,
    password       varchar     NOT NULL,
    create_dt      timestamptz NOT NULL DEFAULT now(),
    update_dt      timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT users_username_key UNIQUE (username),
    CONSTRAINT users_category_group_fkey FOREIGN KEY (category_group)
        REFERENCES category_group (group_name)
);

-- ─────────────────────────────────────────────────────────────────────────────
-- category
-- ─────────────────────────────────────────────────────────────────────────────
CREATE TABLE category (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_name  varchar     NOT NULL,
    category_group varchar     NOT NULL,
    create_dt      timestamptz NOT NULL DEFAULT now(),
    update_dt      timestamptz,

    CONSTRAINT category_category_group_fkey FOREIGN KEY (category_group)
        REFERENCES category_group (group_name)
);

-- ─────────────────────────────────────────────────────────────────────────────
-- asset
--
-- "user" is quoted everywhere because USER is a reserved word in SQL.
-- ON DELETE RESTRICT on category_id is what makes the repository's 23503 ->
-- ErrReferenced -> 409 path reachable: deleting a category that still has assets
-- is refused by the database rather than silently orphaning rows.
-- ─────────────────────────────────────────────────────────────────────────────
CREATE TABLE asset (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asset_code    varchar     NOT NULL,
    asset_name    varchar     NOT NULL,
    brand         varchar,
    serial_number varchar,
    status        varchar     NOT NULL,
    location      varchar     NOT NULL,
    "user"        varchar,
    purchase_date date,
    description   varchar,
    create_dt     timestamptz NOT NULL DEFAULT now(),
    update_dt     timestamptz NOT NULL DEFAULT now(),
    category_id   bigint      NOT NULL,

    CONSTRAINT asset_asset_code_key UNIQUE (asset_code),
    CONSTRAINT asset_category_id_fkey FOREIGN KEY (category_id)
        REFERENCES category (id)
);

-- ─────────────────────────────────────────────────────────────────────────────
-- Indexes
--
-- Every column GetAssetList can filter or sort by. Without these, each listing
-- request is a sequential scan over the whole table — invisible at ten rows,
-- not at a hundred thousand.
-- ─────────────────────────────────────────────────────────────────────────────
CREATE INDEX asset_category_id_idx   ON asset (category_id);
CREATE INDEX asset_status_idx        ON asset (status);
CREATE INDEX asset_purchase_date_idx ON asset (purchase_date DESC);
CREATE INDEX category_group_idx      ON category (category_group);
CREATE INDEX users_category_group_idx ON users (category_group);
